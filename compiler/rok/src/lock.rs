//! `Rok.lock`: the exact commit (and its content hash) of every git
//! package the build uses. Path packages are not pinned: they are always
//! their current content.

use std::path::Path;

use rokc_toml::Value;

use crate::manifest::GitRef;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Locked {
    pub name: String,
    pub url: String,
    pub reference: GitRef,
    pub commit: String,
    /// Git tree hash of the package's files.
    pub tree: String,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Lock {
    pub packages: Vec<Locked>,
}

impl Lock {
    pub fn find(&self, name: &str) -> Option<&Locked> {
        self.packages.iter().find(|p| p.name == name)
    }

    pub fn read(path: &Path) -> Result<Option<Self>, String> {
        match std::fs::read_to_string(path) {
            Ok(text) => Self::parse(&text, &path.display().to_string()).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(format!("cannot read {}: {e}", path.display())),
        }
    }

    pub fn parse(text: &str, file: &str) -> Result<Self, String> {
        let root = rokc_toml::parse(text).map_err(|e| e.render(text, file))?;
        let bad = |msg: &str| format!("{file}: {msg}; delete it and run `rok update`");
        match root.get("version").map(|v| &v.value) {
            Some(Value::Integer(1)) => {}
            _ => return Err(bad("unsupported lockfile version")),
        }
        let mut packages = Vec::new();
        for item in root
            .get("package")
            .and_then(|p| p.value.as_array())
            .unwrap_or(&[])
        {
            let t = item
                .value
                .as_table()
                .ok_or_else(|| bad("bad [[package]]"))?;
            let s = |k: &str| t.get(k).and_then(|v| v.value.as_str()).map(str::to_owned);
            let field = |k: &str| s(k).ok_or_else(|| bad(&format!("[[package]] without `{k}`")));
            let reference = match (s("rev"), s("tag"), s("branch")) {
                (Some(r), None, None) => GitRef::Rev(r),
                (None, Some(t), None) => GitRef::Tag(t),
                (None, None, Some(b)) => GitRef::Branch(b),
                _ => GitRef::Default,
            };
            packages.push(Locked {
                name: field("name")?,
                url: field("git")?,
                reference,
                commit: field("commit")?,
                tree: field("tree")?,
            });
        }
        Ok(Self { packages })
    }

    /// Deterministic text: packages sorted by name, fixed key order.
    pub fn to_text(&self) -> String {
        let q = |s: &str| rokc_toml::format_value(&Value::String(s.to_owned()));
        let mut pkgs: Vec<&Locked> = self.packages.iter().collect();
        pkgs.sort_by(|a, b| a.name.cmp(&b.name));
        let mut out = String::from(
            "# Rok.lock: generated by `rok`; do not edit. Commit it with your sources.\n\
             version = 1\n",
        );
        for p in pkgs {
            out.push_str(&format!(
                "\n[[package]]\nname = {}\ngit = {}\n",
                q(&p.name),
                q(&p.url)
            ));
            if let Some((k, v)) = p.reference.pair() {
                out.push_str(&format!("{k} = {}\n", q(v)));
            }
            out.push_str(&format!(
                "commit = {}\ntree = {}\n",
                q(&p.commit),
                q(&p.tree)
            ));
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip_sorted() {
        let lock = Lock {
            packages: vec![
                Locked {
                    name: "z".into(),
                    url: "file:///z".into(),
                    reference: GitRef::Default,
                    commit: "c1".into(),
                    tree: "t1".into(),
                },
                Locked {
                    name: "a".into(),
                    url: "https://x/a.git".into(),
                    reference: GitRef::Branch("main".into()),
                    commit: "c2".into(),
                    tree: "t2".into(),
                },
            ],
        };
        let text = lock.to_text();
        assert!(text.find("name = \"a\"").unwrap() < text.find("name = \"z\"").unwrap());
        assert!(text.contains("branch = \"main\"\ncommit = \"c2\"\ntree = \"t2\"\n"));
        let back = Lock::parse(&text, "Rok.lock").unwrap();
        assert_eq!(back.find("a"), lock.find("a"));
        assert_eq!(back.to_text(), text);
        assert!(Lock::parse("version = 2", "Rok.lock").is_err());
    }
}
